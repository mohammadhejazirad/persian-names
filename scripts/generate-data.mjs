import { readFile, writeFile } from 'node:fs/promises';
import { gunzipSync } from 'node:zlib';

const SOURCE_PATH = new URL('../src/assets/persian_names.json.gz', import.meta.url);
const OUTPUT_PATH = new URL('../src/generated-data.ts', import.meta.url);
const ALLOWED_NAME = /^\p{Script=Arabic}+$/u;

// Keep this in sync with src/normalize.ts. The generator test catches drift.
function normalizeName(value) {
  return value
    .normalize('NFKC')
    .trim()
    .replace(/[\u0610-\u061a\u064b-\u065f\u0670\u06d6-\u06ed\u0640]/g, '')
    .replace(/[يى]/g, 'ی')
    .replace(/ك/g, 'ک')
    .replace(/ة/g, 'ه')
    .replace(/[أإٱ]/g, 'ا')
    .replace(/[\s\u200c-\u200f\u202a-\u202e\u2066-\u2069_-]+/g, '');
}

function extractNames(rawName) {
  const withoutIndex = rawName
    .normalize('NFKC')
    .replace(/\s*[0-9۰-۹]+\s*$/u, '')
    .trim();
  const candidates = [withoutIndex.replace(/\s*\([^)]*\)\s*$/u, '')];

  for (const match of withoutIndex.matchAll(/\(([^)]+)\)/gu)) {
    candidates.push(match[1]);
  }

  return candidates
    .flatMap((candidate) => candidate.split(/[،,/]/u))
    .map(normalizeName)
    .filter(Boolean);
}

function sortNames(names) {
  return names.sort((left, right) => (left < right ? -1 : left > right ? 1 : 0));
}

function encode(names) {
  return JSON.stringify(sortNames(names).join('|'));
}

const compressed = await readFile(SOURCE_PATH);
const records = JSON.parse(gunzipSync(compressed).toString('utf8'));

if (!Array.isArray(records)) throw new TypeError('The names dataset must be an array.');

const genders = new Map();

for (const [position, record] of records.entries()) {
  if (
    !record ||
    typeof record !== 'object' ||
    typeof record.n !== 'string' ||
    (record.g !== 'm' && record.g !== 'f')
  ) {
    throw new TypeError(`Invalid dataset record at index ${position}.`);
  }

  const gender = record.g === 'm' ? 1 : 2;
  for (const name of extractNames(record.n)) {
    if (!ALLOWED_NAME.test(name) || name.includes('|')) {
      throw new TypeError(`Invalid normalized name at index ${position}: ${name}`);
    }
    genders.set(name, (genders.get(name) ?? 0) | gender);
  }
}

const male = [];
const female = [];
const unisex = [];

for (const [name, gender] of genders) {
  if (gender === 1) male.push(name);
  else if (gender === 2) female.push(name);
  else if (gender === 3) unisex.push(name);
  else throw new RangeError(`Invalid merged gender for ${name}: ${gender}`);
}

const generated = `/* This file is generated by scripts/generate-data.mjs. Do not edit. */
/** @internal */
export const SOURCE_RECORD_COUNT: number = ${records.length};
/** @internal */
export const UNIQUE_NAME_COUNT: number = ${genders.size};
/** @internal */
export const MALE_NAMES: string = ${encode(male)};
/** @internal */
export const FEMALE_NAMES: string = ${encode(female)};
/** @internal */
export const UNISEX_NAMES: string = ${encode(unisex)};
`;

let previous = '';
try {
  previous = await readFile(OUTPUT_PATH, 'utf8');
} catch (error) {
  if (error?.code !== 'ENOENT') throw error;
}

if (previous !== generated) await writeFile(OUTPUT_PATH, generated, 'utf8');

console.log(
  `Generated ${genders.size.toLocaleString('en-US')} unique names from ` +
    `${records.length.toLocaleString('en-US')} records ` +
    `(${male.length.toLocaleString('en-US')} male, ` +
    `${female.length.toLocaleString('en-US')} female, ` +
    `${unisex.length.toLocaleString('en-US')} both).`
);
