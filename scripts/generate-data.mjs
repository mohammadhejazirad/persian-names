import { readFile, writeFile } from 'node:fs/promises';
import { gunzipSync } from 'node:zlib';
import { englishFor, loadFoldedEnglish } from './lib/english.mjs';
import { GOLD_BY_NAME } from './lib/gold.mjs';
import { ORIGIN_CODE, originFor } from './lib/origins.mjs';

const SOURCE_PATH = new URL('../src/assets/persian_names.json.gz', import.meta.url);
const OUTPUT_PATH = new URL('../src/generated-data.ts', import.meta.url);
const ALLOWED_NAME = /^\p{Script=Arabic}+$/u;

// Keep this in sync with src/normalize.ts. The generator test catches drift.
function normalizeName(value) {
  return value
    .normalize('NFKC')
    .trim()
    .replace(/[\u0610-\u061a\u064b-\u065f\u0670\u06d6-\u06ed\u0640]/g, '')
    .replace(/[يى]/g, 'ی')
    .replace(/ك/g, 'ک')
    .replace(/ة/g, 'ه')
    .replace(/[أإٱ]/g, 'ا')
    .replace(/[\s\u200c-\u200f\u202a-\u202e\u2066-\u2069_-]+/g, '');
}

function extractNames(rawName) {
  const withoutIndex = rawName
    .normalize('NFKC')
    .replace(/\s*[0-9۰-۹]+\s*$/u, '')
    .trim();
  const candidates = [withoutIndex.replace(/\s*\([^)]*\)\s*$/u, '')];

  for (const match of withoutIndex.matchAll(/\(([^)]+)\)/gu)) {
    candidates.push(match[1]);
  }

  return candidates
    .flatMap((candidate) => candidate.split(/[،,/]/u))
    .map(normalizeName)
    .filter(Boolean);
}

const ENGLISH_PATTERN = /^[A-Z][a-z]+$/u;

function consonantRun(english) {
  const value = english.toLowerCase();
  let run = 0;
  let max = 0;
  for (let index = 0; index < value.length; index += 1) {
    if ('aeiou'.includes(value[index] ?? '')) {
      run = 0;
      continue;
    }
    run += 1;
    const pair = value.slice(index, index + 2);
    if (pair === 'sh' || pair === 'ch' || pair === 'kh' || pair === 'zh' || pair === 'gh') {
      index += 1;
    }
    if (run > max) max = run;
  }
  return max;
}

const compressed = await readFile(SOURCE_PATH);
const records = JSON.parse(gunzipSync(compressed).toString('utf8'));

if (!Array.isArray(records)) throw new TypeError('The names dataset must be an array.');

const genders = new Map();

for (const [position, record] of records.entries()) {
  if (
    !record ||
    typeof record !== 'object' ||
    typeof record.n !== 'string' ||
    (record.g !== 'm' && record.g !== 'f')
  ) {
    throw new TypeError(`Invalid dataset record at index ${position}.`);
  }

  const gender = record.g === 'm' ? 1 : 2;
  for (const name of extractNames(record.n)) {
    if (!ALLOWED_NAME.test(name) || name.includes('|')) {
      throw new TypeError(`Invalid normalized name at index ${position}: ${name}`);
    }
    genders.set(name, (genders.get(name) ?? 0) | gender);
  }
}

const folded = await loadFoldedEnglish();
const names = new Set(genders.keys());
const originCounts = new Map();
const rows = [];

for (const [name, gender] of genders) {
  if (gender !== 1 && gender !== 2 && gender !== 3) {
    throw new RangeError(`Invalid merged gender for ${name}: ${gender}`);
  }

  const origin = originFor(name);
  const code = ORIGIN_CODE[origin];
  if (!code) throw new RangeError(`Invalid origin for ${name}: ${origin}`);

  const expected = GOLD_BY_NAME.get(name);
  if (expected && expected.origin !== origin) {
    throw new RangeError(`Origin mismatch for ${name}: ${origin}, expected ${expected.origin}`);
  }
  if (expected && expected.gender !== gender) {
    throw new RangeError(`Gender mismatch for ${name}: ${gender}, expected ${expected.gender}`);
  }

  const english = englishFor(name, names, folded);
  if (expected && expected.english !== english) {
    throw new RangeError(`English mismatch for ${name}: ${english}, expected ${expected.english}`);
  }
  if (!ENGLISH_PATTERN.test(english) || english.includes('|') || english.includes('\t')) {
    throw new RangeError(`Invalid English spelling for ${name}: ${english}`);
  }
  if (consonantRun(english) >= 4) {
    throw new RangeError(`English spelling for ${name} is missing vowels: ${english}`);
  }

  originCounts.set(origin, (originCounts.get(origin) ?? 0) + 1);
  rows.push(`${name}\t${english}\t${gender}${code}`);
}

rows.sort((left, right) => (left < right ? -1 : left > right ? 1 : 0));

const generated = `/* This file is generated by scripts/generate-data.mjs. Do not edit. */
/** @internal */
export const SOURCE_RECORD_COUNT: number = ${records.length};
/** @internal */
export const UNIQUE_NAME_COUNT: number = ${genders.size};
/** @internal */
export const RECORDS: string = ${JSON.stringify(rows.join('|'))};
`;

let previous = '';
try {
  previous = await readFile(OUTPUT_PATH, 'utf8');
} catch (error) {
  if (error?.code !== 'ENOENT') throw error;
}

if (previous !== generated) await writeFile(OUTPUT_PATH, generated, 'utf8');

const genderCounts = [0, 0, 0, 0];
for (const gender of genders.values()) genderCounts[gender] += 1;

console.log(
  `Generated ${genders.size.toLocaleString('en-US')} unique names from ` +
    `${records.length.toLocaleString('en-US')} records ` +
    `(${genderCounts[1].toLocaleString('en-US')} male, ` +
    `${genderCounts[2].toLocaleString('en-US')} female, ` +
    `${genderCounts[3].toLocaleString('en-US')} both).`
);
console.log(
  `Origins: ${[...originCounts.entries()]
    .sort((left, right) => right[1] - left[1])
    .map(([origin, count]) => `${origin} ${count}`)
    .join(', ')}.`
);
